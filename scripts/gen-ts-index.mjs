#!/usr/bin/env node
// Part of `pnpm gen:types`. ts-rs writes one .ts file per Rust type into src/ipc/generated/;
// this script writes the barrel (index.ts) that re-exports them all.
//
//   node scripts/gen-ts-index.mjs          write src/ipc/generated/index.ts
//   node scripts/gen-ts-index.mjs clean    delete src/ipc/generated first, so a type that no
//                                          longer exists in Rust does not linger
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "ipc", "generated");

if (process.argv[2] === "clean") {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  process.exit(0);
}

/** Every generated type file, as a path relative to `dir` without the extension. */
function modules(sub = "") {
  const out = [];
  for (const entry of readdirSync(join(dir, sub), { withFileTypes: true })) {
    const rel = sub ? `${sub}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...modules(rel));
    else if (entry.name.endsWith(".ts") && rel !== "index.ts") out.push(rel.slice(0, -3));
  }
  return out;
}

const lines = modules()
  .sort((a, b) => a.localeCompare(b, "en"))
  .map((m) => `export type { ${m.split("/").pop()} } from "./${m}";`);

writeFileSync(
  join(dir, "index.ts"),
  `// Generated by scripts/gen-ts-index.mjs (pnpm gen:types). Do not edit this file manually.\n${lines.join("\n")}\n`,
);
